def layout(spread_name):
    """返回牌阵的几何布局 {cols, rows, cells:[[col,row,(rot)], ...]}。

    没有定义、或坐标数量对不上牌位数时，退化成一行排开——保证永远能画出来。
    """
    d = SPREAD_META.get(spread_name)
    if not d:
        return None
    n = len(d["positions"])
    lay = LAYOUTS.get(spread_name)
    if not lay or len(lay["cells"]) != n:
        return {"cols": n, "rows": 1, "cells": [[i + 1, 1] for i in range(n)]}
    out = {"cols": int(lay["cols"]), "rows": int(lay["rows"]),
           "cells": [[int(c[0]), int(c[1])] + ([int(c[2])] if len(c) > 2 else [])
                     for c in lay["cells"]]}
    if lay.get("gap"):
        out["gap"] = [int(lay["gap"][0]), int(lay["gap"][1])]
    return out


def describe(spread_name):
    """返回一个牌阵的说明文本（给模型看），找不到返回空串。"""
    d = SPREAD_META.get(spread_name)
    if not d:
        return ""
    lines = ["牌阵：%s（%s 张牌）" % (d["name"], len(d["positions"])),
             "用法：%s" % d["desc"], "牌位与含义："]
    for i, (pos, meaning) in enumerate(d["positions"], 1):
        lines.append("  %d. %s —— %s" % (i, pos, meaning))
    return "\n".join(lines)


def catalogue():
    """给提示词用的牌阵清单（名称 + 张数 + 一句话用途）。"""
    out = []
    for d in SPREAD_DEFS:
        out.append("- %s（%d 张，%s）：%s"
                   % (d["name"], len(d["positions"]), d["category"], d["desc"]))
    return "\n".join(out)


def list_spreads():
    """给前端/API 用的结构化清单。"""
    return [{
        "name": d["name"],
        "category": d["category"],
        "desc": d["desc"],
        "count": len(d["positions"]),
        "positions": [p[0] for p in d["positions"]],
        "layout": layout(d["name"]),
    } for d in SPREAD_DEFS]
