# name -> [牌位名, ...]（保持 tools.py 原有接口不变）
SPREADS = {d["name"]: [p[0] for p in d["positions"]] for d in SPREAD_DEFS}

# name -> 定义，给提示词和前端用
SPREAD_META = {d["name"]: d for d in SPREAD_DEFS}


def describe(spread_name):
    """返回一个牌阵的说明文本（给模型看），找不到返回空串。"""
    d = SPREAD_META.get(spread_name)
    if not d:
        return ""
    lines = ["牌阵：%s（%s 张牌）" % (d["name"], len(d["positions"])),
             "用法：%s" % d["desc"], "牌位与含义："]
    for i, (pos, meaning) in enumerate(d["positions"], 1):
        lines.append("  %d. %s —— %s" % (i, pos, meaning))
    return "\n".join(lines)


def catalogue():
    """给提示词用的牌阵清单（名称 + 张数 + 一句话用途）。"""
    out = []
    for d in SPREAD_DEFS:
        out.append("- %s（%d 张，%s）：%s"
                   % (d["name"], len(d["positions"]), d["category"], d["desc"]))
    return "\n".join(out)


def list_spreads():
    """给前端/API 用的结构化清单。"""
    return [{
        "name": d["name"],
        "category": d["category"],
        "desc": d["desc"],
        "count": len(d["positions"]),
        "positions": [p[0] for p in d["positions"]],
    } for d in SPREAD_DEFS]
