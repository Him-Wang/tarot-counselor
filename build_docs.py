"""
build_docs.py — bundle persona + knowledge into JS files for the static site.

Run from anywhere:  python build_docs.py
Outputs docs/persona.js and docs/knowledge.js consumed by docs/index.html.
"""

import os
import json

BASE = os.path.dirname(os.path.abspath(__file__))
DOCS = os.path.join(BASE, "docs")
PERSONA = os.path.join(BASE, "prompts", "persona.zh.md")
KDIR = os.path.join(BASE, "knowledge")


def read(path):
    with open(path, "r", encoding="utf-8") as f:
        return f.read()


def js_string(s):
    # json.dumps produces a valid JS string literal for our purposes
    return json.dumps(s, ensure_ascii=False)


def main():
    os.makedirs(DOCS, exist_ok=True)

    persona = read(PERSONA).strip()
    with open(os.path.join(DOCS, "persona.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by build_docs.py — do not edit by hand.\n")
        f.write("window.PERSONA_TEXT = " + js_string(persona) + ";\n")

    docs = []
    for root, _dirs, files in os.walk(KDIR):
        for fn in files:
            if not fn.lower().endswith((".md", ".txt")) or fn.upper() == "INDEX.MD":
                continue
            path = os.path.join(root, fn)
            rel = os.path.relpath(path, KDIR).replace("\\", "/")
            docs.append({"rel": rel, "text": read(path).strip()})
    docs.sort(key=lambda d: d["rel"])

    with open(os.path.join(DOCS, "knowledge.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by build_docs.py — do not edit by hand.\n")
        f.write("window.KNOWLEDGE_DOCS = " + js_string(docs) + ";\n")

    print("Wrote docs/persona.js (%d chars) and docs/knowledge.js (%d docs)" % (len(persona), len(docs)))


if __name__ == "__main__":
    main()
